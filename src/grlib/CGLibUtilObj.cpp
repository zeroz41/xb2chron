CGLibUtilObj::CGLibUtilObj() {}

CGLibUtilObj::~CGLibUtilObj() {}

void CGLibUtilObj::setup() {
    m_decShader.createCopyShader(CGLibMemHandle::s_hMemHandle, s_utilShader, true);
    CGLibVtxAttr attributes[3];
    attributes[0].format = 0x22;
    attributes[0].location = 0;
    attributes[0].offset = 0;
    attributes[0].stream = 0;
    attributes[1].format = 0x25;
    attributes[1].location = 1;
    attributes[1].offset = 0xC;
    attributes[1].stream = 0;
    attributes[2].format = 0x16;
    attributes[2].location = 2;
    attributes[2].offset = 0x10;
    attributes[2].stream = 0;
    m_vtxFetches[0].createFetchObj(attributes, 3);
    m_vtxFetches[1].createFetchObj(attributes, 2);
    attributes[0].format = 0x16;
    attributes[0].location = 0;
    attributes[0].offset = 0;
    attributes[0].stream = 0;
    attributes[1].format = 0x16;
    attributes[1].location = 0;
    attributes[1].offset = 8;
    attributes[1].stream = 0;
    m_vtxFetches[2].createFetchObj(attributes, 2);
    m_samplers[0].initSampler(GrlTexClamp(2), GrlTexMagFilterType(1));
    m_samplers[0].updateData();
    m_samplers[1].initSampler(GrlTexClamp(2), GrlTexMagFilterType(0));
    m_samplers[1].updateData();
    m_vtxVertex.createCopyVertexBuff(s_quadVertices, sizeof(s_quadVertices), sizeof(s_quadVertices[0]));
    m_vtxIndex.createCopyIndexBuff(s_quadIndices, 4, GrlPrimitiveType(7), GrlIndexFormat(1));
}

void CGLibUtilObj::release() {
    m_decShader.release();
    m_vtxFetches[0].release();
    m_vtxFetches[1].release();
    m_vtxFetches[2].release();
    m_samplers[0].release();
    m_samplers[1].release();
    m_vtxVertex.release();
    m_vtxIndex.release();
}

